"""Chilean variables per grid cell (owners: Pancho delivers rasters, Rojas runs this script).

Inputs (GeoTIFF, EPSG:4326):
  --dem     ASTER GDEM v3 mosaic of continental Chile
  --precip  mean annual precipitation 2001-2024 in mm/yr from GPM IMERG Final V07 (monthly sums)
  --volcanic optional 0/1 raster of volcanic units digitised from SERNAGEOMIN 1:1,000,000
Output: data/processed/master.csv with cell_id, slope_p90_deg, relief_m, rough_sd_deg,
        precip_mm_yr, volcanic_unit (+ .metadata.json).

The DEM is reprojected to UTM 19S (EPSG:32719) at 463 m with average resampling.
Projection distortion has been checked for the bounded mainland pilot (-76..-66 lon,
-56..-17 lat): local scale error is under 0.7% at sampled bounding points. Do NOT
reuse this national shortcut for Easter Island or areas outside the stated bbox.

AI-Assisted: Claude (draft of this script; reviewed and run by the team).
"""
import argparse, json
from pathlib import Path
import numpy as np
import pandas as pd
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from features.terrain import BASE_RES_M, centered_windows

UTM = "EPSG:32719"


def dem_to_utm(path):
    import rasterio
    from rasterio.warp import calculate_default_transform, reproject, Resampling
    with rasterio.open(path) as src:
        tr, w, h = calculate_default_transform(src.crs, UTM, src.width, src.height, *src.bounds,
                                               resolution=BASE_RES_M)
        out = np.full((h, w), np.nan, dtype="float32")
        reproject(rasterio.band(src, 1), out, src_transform=src.transform, src_crs=src.crs,
                  dst_transform=tr, dst_crs=UTM, resampling=Resampling.average, dst_nodata=np.nan)
    return out, tr


def sample_raster(path, lon, lat):
    import rasterio
    with rasterio.open(path) as ds:
        if ds.crs is None:
            raise ValueError(f"Missing CRS in {path}")
        from pyproj import Transformer
        if ds.crs.to_epsg() == 4326:
            coords = zip(lon, lat)
        else:
            x, y = Transformer.from_crs("EPSG:4326", ds.crs, always_xy=True).transform(lon, lat)
            coords = zip(x, y)
        vals = np.array([v[0] for v in ds.sample(coords)], float)
        if ds.nodata is not None:
            vals[vals == ds.nodata] = np.nan
    return vals


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--grid", default="data/processed/grid.csv")
    ap.add_argument("--dem", required=True)
    ap.add_argument("--precip", required=True)
    ap.add_argument("--volcanic", default=None)
    ap.add_argument("--out", default="data/processed/master.csv")
    a = ap.parse_args()
    from pyproj import Transformer
    import rasterio
    grid = pd.read_csv(a.grid)
    dem, tr = dem_to_utm(a.dem)
    x, y = Transformer.from_crs("EPSG:4326", UTM, always_xy=True).transform(grid.lon_c.values, grid.lat_c.values)
    rows, cols = rasterio.transform.rowcol(tr, x, y)
    feats = pd.DataFrame(centered_windows(dem, np.array(rows), np.array(cols)))
    master = pd.concat([grid[["cell_id"]].reset_index(drop=True), feats], axis=1)
    master["precip_mm_yr"] = sample_raster(a.precip, grid.lon_c.values, grid.lat_c.values)
    master["volcanic_unit"] = sample_raster(a.volcanic, grid.lon_c.values, grid.lat_c.values) if a.volcanic else np.nan
    if master["precip_mm_yr"].notna().sum() == 0:
        raise ValueError("No valid precipitation samples: check raster, bounds and CRS")
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    master.to_csv(a.out, index=False)
    Path(a.out).with_suffix(".metadata.json").write_text(json.dumps({
        "dem": a.dem, "precip": a.precip, "volcanic": a.volcanic, "base_res_m": BASE_RES_M,
        "projection_for_slope": UTM, "window_km": 5,
        "ai": "script drafted with AI assistance; no data values generated by AI"}, indent=2))
    print(master.describe().T)


if __name__ == "__main__":
    main()
